import { chromium } from 'playwright';
import { readFileSync } from 'fs';
const S = process.argv[2], OUT = process.argv[3], MODE = process.argv[4] || 'desk', SCHEME = process.argv[5] || 'light', ORG = process.argv[6] || 'heart';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const W = MODE === 'phone' ? 400 : 1440, H = MODE === 'phone' ? 860 : 900;
const page = await (await browser.newContext({ viewport: { width: W, height: H }, colorScheme: SCHEME })).newPage();
page.setDefaultTimeout(180000);
page.on('pageerror', e => console.log('pageerror:', e.message));
page.on('console', m => { if (m.type() === 'error' && !m.text().includes('404') && !m.text().includes('ERR_FAILED')) console.log('console:', m.text()); });
await page.route('**/three.min.js', r => r.fulfill({ body: readFileSync(S + '/three/package/build/three.min.js'), contentType: 'text/javascript' }));
await page.route('**/OrbitControls.js', r => r.fulfill({ body: readFileSync(S + '/three/package/examples/js/controls/OrbitControls.js'), contentType: 'text/javascript' }));
await page.route('https://fonts.**', r => r.abort());
await page.route('**/anatomy-atlas.html', r => r.fulfill({ body: readFileSync(S + '/site/anatomy-atlas.html'), contentType: 'text/html; charset=utf-8' }));
const tag = `${MODE}-${SCHEME}`;
const shot = async n => page.screenshot({ path: `${OUT}/ui-${tag}-${n}.png`, timeout: 180000 });
const wait = ms => page.waitForTimeout(ms);
await page.goto('http://127.0.0.1:8765/anatomy-atlas.html');
await page.waitForFunction(() => getComputedStyle(document.getElementById('load')).opacity === '0');
await wait(3500); await shot('1-body');
if (ORG.startsWith('bones-')) { await page.click('#modeSwitch [data-mode="bones"]'); await wait(2500); await shot('1b-bones-mode'); }
await page.click(`.ocard[data-key="${({lungs:'right-lung',gut:'stomach',urinary:'kidney','repro-male':'testis'})[ORG] || ORG}"]`); await wait(2500); await shot('2-body-selected');
await page.click('#openOrgan');
await page.waitForFunction(() => document.getElementById('hLoad').hidden && document.querySelectorAll('#partList .row').length > 0);
await wait(4000); await shot('3-learn');
await page.click('#tabParts'); await wait(600); await page.click('#partList .row'); await wait(2500); await shot('4-part');
await page.click('#tabParts'); await wait(800); await shot('5-parts-tab');
await page.click('#tabFlow'); await wait(2500); await shot('6-tour');
await page.click('#tabNotes'); await wait(800); await shot('7-notes');
await page.click('#navSources'); await wait(1200); await shot('8-sources');
console.log('done', tag);
await browser.close();
