import { chromium } from 'playwright';
import { readFileSync } from 'fs';
const S = process.argv[2], OUT = process.argv[3];
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
page.setDefaultTimeout(180000);
page.on('pageerror', e => console.log('pageerror:', e.message));
page.on('console', m => { if (m.type() === 'error') console.log('console:', m.text()); });
await page.route('**/three.min.js', r => r.fulfill({ body: readFileSync(S + '/three/package/build/three.min.js'), contentType: 'text/javascript' }));
await page.route('**/OrbitControls.js', r => r.fulfill({ body: readFileSync(S + '/three/package/examples/js/controls/OrbitControls.js'), contentType: 'text/javascript' }));
await page.route('https://fonts.**', r => r.abort());
await page.route('**/anatomy-atlas.html', r => r.fulfill({ body: readFileSync(S + '/site/anatomy-atlas.html'), contentType: 'text/html; charset=utf-8' }));
const shot = n => page.screenshot({ path: `${OUT}/f-${n}.png` });
const cards = () => page.$$eval('#organList .ocard', b => b.map(x => x.innerText.replace(/\n/g, ' / ')));
await page.goto('http://127.0.0.1:8765/anatomy-atlas.html');
await page.waitForFunction(() => getComputedStyle(document.getElementById('load')).opacity === '0');
await page.click('#sexSwitch [data-sex="female"]');
await page.waitForFunction(() => document.querySelector('#bodyInfo').innerText.includes('Female'));
await page.waitForTimeout(3500); await shot('1-body');
console.log('female organ cards:', await cards());
await page.click('.ocard[data-key="uterus"]'); await page.waitForTimeout(2500); await shot('2-uterus');
await page.click('#openOrgan');
await page.waitForFunction(() => document.getElementById('hLoad').hidden && document.querySelectorAll('#partList .row').length > 0);
await page.waitForTimeout(4000); await shot('3-repro-learn');
await page.click('#tabFlow'); await page.waitForTimeout(2500); await shot('4-repro-tour');
await page.click('#tabNotes'); await page.waitForTimeout(800); await shot('5-repro-notes');
await page.click('#backBody'); await page.waitForTimeout(1500);
console.log('back on body, sex label:', (await page.$eval('#bodyInfo', e => e.innerText)).slice(0, 40));
await page.click('#modeSwitch [data-mode="bones"]'); await page.waitForTimeout(2500); await shot('6-bones');
console.log('female bone cards:', await cards());
await page.click('.ocard[data-key="bones-pelvis"]'); await page.waitForTimeout(1500); await page.click('#openOrgan');
await page.waitForFunction(() => document.getElementById('hLoad').hidden && document.querySelector('#organTitle').textContent.includes('female'));
await page.waitForTimeout(4000); await shot('7-pelvis-f');
await page.click('#backBody'); await page.waitForTimeout(1000);
await page.click('#modeSwitch [data-mode="organs"]'); await page.waitForTimeout(800);
await page.click('.ocard[data-key="heart"]'); await page.waitForTimeout(1500); await page.click('#openOrgan');
await page.waitForFunction(() => document.getElementById('hLoad').hidden && document.querySelector('#organTitle').textContent === 'Heart');
await page.waitForTimeout(2500); await page.click('#tabNotes'); await page.waitForTimeout(600); await shot('8-heart-from-female');
await page.click('#backBody'); await page.waitForTimeout(800);
await page.click('#sexSwitch [data-sex="male"]'); await page.waitForTimeout(2500);
console.log('male cards include penis:', (await cards()).some(c => c.startsWith('Penis')), '; uterus:', (await cards()).some(c => c.startsWith('Uterus')));
await page.click('#navSources'); await page.waitForTimeout(1500); await page.evaluate(() => window.scrollTo(0, 900)); await page.waitForTimeout(400); await shot('9-sources');
await browser.close();
